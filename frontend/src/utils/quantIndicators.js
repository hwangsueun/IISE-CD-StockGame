export const QUANT_INDICATORS = alpha158.map(({ name, expression }) => {
  const family = definitions[name] ? name : name.replace(/\d+$/, '');
  const period = definitions[name] ? null : Number(name.slice(family.length));
  const [group, title, formula, meaning] = definitions[family];
  const fill = (text) => text.replaceAll('{n}', String(period));
  return { name, expression, family, period, group, title: fill(title), formula: fill(formula), meaning };
});

export function filterQuantIndicators({ query = '', group = 'all', period = 'all' } = {}) {
  const terms = query.trim().toLocaleLowerCase('ko-KR').split(/\s+/).filter(Boolean);
  return QUANT_INDICATORS.filter((item) => {
    if (group !== 'all' && item.group !== group) return false;
    if (period !== 'all' && (period === 'today' ? item.period !== null : item.period !== Number(period))) return false;
    const text = `${item.name} ${item.title} ${item.formula} ${item.meaning} ${INDICATOR_GROUPS[item.group]}`.toLocaleLowerCase('ko-KR');
    return terms.every((term) => text.includes(term));
  });
}
