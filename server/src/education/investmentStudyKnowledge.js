const KNOWLEDGE = Object.freeze(LESSONS.map(([id, topic, title, insight, q, correct, wrong], i) => {
  const answer = i % 4;
  const opts = [...wrong];
  opts.splice(answer, 0, correct);
  return Object.freeze({
    id, topic, title, insight,
    quiz: Object.freeze({ chip: topic, q, opts: Object.freeze(opts), answer, explain: insight }),
  });
}));

const BY_ID = new Map(KNOWLEDGE.map((lesson) => [lesson.id, lesson]));
const BY_TEXT = new Map(KNOWLEDGE.map((lesson) => [lesson.insight, lesson]));
// 기존 이벤트 이력도 첫 순환에서 이미 배운 개념으로 인정한다.
const LEGACY_IDS = new Map([
  ['분산 투자는 개별 종목 리스크를 줄여준다.', 'diversify_single'],
  ['금리가 오르면 기업의 이자 부담이 커질 수 있다.', 'macro_interest'],
  ['거래량이 실리지 않은 급등은 오래가지 못하는 경우가 많다.', 'volume_price'],
  ['PER이 낮다고 무조건 저평가는 아니다. 업종 평균과 비교하라.', 'valuation_per'],
]);

/** newest-first resolved event details; 읽기만 하며 DB 스키마나 전역 상태를 바꾸지 않는다. */
function selectStudyKnowledge(history = [], random = Math.random) {
  const studied = history.map((row) => {
    const detail = row?.detail || row;
    return BY_ID.get(detail?.insightId)
      || BY_TEXT.get(detail?.insight)
      || BY_ID.get(LEGACY_IDS.get(detail?.insight));
  }).filter(Boolean);
  const counts = new Map();
  for (const lesson of studied) counts.set(lesson.id, (counts.get(lesson.id) || 0) + 1);

  // 처음에는 미학습 지식부터 전부 순환하고, 이후에도 학습 횟수가 적은 지식을 우선한다.
  const minimum = Math.min(...KNOWLEDGE.map((lesson) => counts.get(lesson.id) || 0));
  let candidates = KNOWLEDGE.filter((lesson) => (counts.get(lesson.id) || 0) === minimum);
  const recentIds = new Set(studied.slice(0, 12).map((lesson) => lesson.id));
  const fresh = candidates.filter((lesson) => !recentIds.has(lesson.id));
  if (fresh.length) candidates = fresh;
  const recentTopics = new Set(studied.slice(0, 2).map((lesson) => lesson.topic));
  const differentTopics = candidates.filter((lesson) => !recentTopics.has(lesson.topic));
  if (differentTopics.length) candidates = differentTopics;
  const draw = Number(random());
  const unit = Number.isFinite(draw) ? Math.min(Math.max(draw, 0), 1 - Number.EPSILON) : 0;
  return candidates[Math.floor(unit * candidates.length)];
}

module.exports = { KNOWLEDGE, selectStudyKnowledge };
