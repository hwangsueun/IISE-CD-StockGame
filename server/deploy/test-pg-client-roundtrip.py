 ('11111111-2222-4333-8444-555555555555',9007199254740993123456789,'{"strategy":"이름 보존","nested":[null,false,123456789012345678901234567890]}',decode('0001ff80','hex'),'주식·전략\줄바꿈','2016-09-26T00:00:00+09',ARRAY['은행','a,b',NULL],true),
 ('66666666-7777-4888-8999-aaaaaaaaaaaa',-123456789012345678901234567890,'{"zero":0,"empty":"","nullable":null}',decode('','hex'),'둘째',NULL,NULL,false),
