SNAPSHOT = r'''
SELECT jsonb_build_object(
 'parent',(SELECT jsonb_agg(to_jsonb(p) ORDER BY id) FROM preserved.parent p),
 'child',(SELECT jsonb_agg(to_jsonb(c) ORDER BY parent_id,ordinal) FROM preserved.child c),
 'custom_sequence',(SELECT jsonb_build_array(last_value,is_called) FROM preserved.custom_sequence),
 'identity_sequence',(SELECT jsonb_build_array(last_value,is_called) FROM preserved.parent_id_seq),
 'view',(SELECT jsonb_agg(to_jsonb(v) ORDER BY id) FROM preserved.amounts v),
 'materialized',(SELECT jsonb_agg(to_jsonb(m)) FROM preserved.row_count m),
 'function',pg_get_functiondef('preserved.echo(text)'::regprocedure),
 'large_objects',(SELECT jsonb_agg(jsonb_build_array(loid,pageno,encode(data,'hex')) ORDER BY loid,pageno) FROM pg_largeobject),
 'constraints',(SELECT jsonb_agg(pg_get_constraintdef(oid) ORDER BY conname) FROM pg_constraint WHERE connamespace='preserved'::regnamespace),
 'extension',(SELECT extversion FROM pg_extension WHERE extname='pgcrypto')
)::text;
'''
NODE_ROUNDTRIP = r'''
const { getPgTools } = require('/bundle/pg-client.cjs');
const { spawn } = require('node:child_process');
const fs = require('node:fs/promises');
async function run(tool, args, database) {
  const { command, argsPrefix } = await getPgTools(tool);
  const env = { ...process.env, PGHOST:'pg-bundle-source', PGPORT:'5432', PGUSER:'postgres',
    PGDATABASE:database, PGSSLMODE:'require', PGCONNECT_TIMEOUT:'10' };
  return new Promise((resolve,reject) => {
    const child=spawn(command,[...argsPrefix,...args],{env,stdio:['ignore','pipe','pipe']});
    let out='',err='';
    child.stdout.on('data',b=>out+=b); child.stderr.on('data',b=>err+=b);
    child.on('error',reject);child.on('close',code=>code===0?resolve({out,err}):reject(new Error(`${tool} failed ${code}: ${err}`)));
  });
}
(async()=>{
  const dump=await run('pg_dump',['--format=custom','--no-owner','--no-acl','--file=/review/fixture.dump'],'bundle_source');
  const listed=await run('pg_restore',['--list','/review/fixture.dump'],'bundle_source');
  if(!listed.out.includes('preserved'))throw new Error('Archive TOC missing fixture schema');
  const restore=await run('pg_restore',['--exit-on-error','--single-transaction','--no-owner','--no-acl','--dbname=bundle_restored','/review/fixture.dump'],'bundle_restored');
  await fs.writeFile('/review/client-execution.json',JSON.stringify({passed:true,tls:'require',dumpStderr:dump.err,restoreStderr:restore.err,tocIncludesSchema:true})+'\n');
})().catch(e=>{console.error(e.message);process.exitCode=1});
'''


def docker(args, **options):
    return subprocess.run(['docker', *args], check=True, capture_output=True, text=True, timeout=90, **options)


def test(output_dir, node_image):
    output_dir = Path(output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    name = 'antsurvival-pg-client-test-' + uuid.uuid4().hex[:12]
    network = name + '-network'
    password = uuid.uuid4().hex + uuid.uuid4().hex
    before = docker(['ps', '-q']).stdout.splitlines()
    started = False
    network_created = False
    try:
        boot = r'''set -eu
openssl req -x509 -newkey rsa:2048 -nodes -keyout /tmp/server.key -out /tmp/server.crt -subj /CN=pg-bundle-source -days 1 >/dev/null 2>&1
chown postgres:postgres /tmp/server.key /tmp/server.crt
chmod 600 /tmp/server.key
exec docker-entrypoint.sh postgres -c ssl=on -c ssl_cert_file=/tmp/server.crt -c ssl_key_file=/tmp/server.key
'''
        docker(['network', 'create', '--internal', network])
        network_created = True
        docker(['run', '--detach', '--rm', '--name', name, '--platform=linux/amd64', '--network', network,
                '--network-alias', 'pg-bundle-source',
                '--tmpfs', '/var/lib/postgresql/data:rw,nosuid,nodev', '-e', 'POSTGRES_HOST_AUTH_METHOD=scram-sha-256',
                '-e', 'POSTGRES_PASSWORD=' + password, '-e', 'POSTGRES_INITDB_ARGS=--auth-host=scram-sha-256',
                '--entrypoint=/bin/sh', package.IMAGE, '-c', boot])
        started = True
        for _ in range(60):
            ready = subprocess.run(['docker', 'exec', name, 'pg_isready', '-h', 'localhost', '-U', 'postgres'],
                                   capture_output=True, timeout=5)
            if ready.returncode == 0:
                break
            time.sleep(0.25)
        else:
            raise RuntimeError('Temporary PostgreSQL server did not become ready')
        def sql(database, statement):
            return docker(['exec', '-i', name, 'psql', '-X', '-v', 'ON_ERROR_STOP=1', '-U', 'postgres',
                           '-d', database, '-A', '-t'], input=statement).stdout.strip()
        sql('postgres', DATABASES)
        if sql('postgres', "SELECT rolpassword LIKE 'SCRAM-SHA-256$%' FROM pg_authid WHERE rolname='postgres';") != 't':
            raise AssertionError('The disposable fixture did not enable SCRAM authentication')
        sql('bundle_source', FIXTURE)
        original = json.loads(sql('bundle_source', SNAPSHOT))
        script = output_dir / 'roundtrip-client.cjs'
        script.write_text(NODE_ROUNDTRIP)
        docker(['run', '--rm', '--platform=linux/amd64', '--network', network, '--read-only',
                '--tmpfs', '/tmp:rw,nosuid,nodev,exec', '-e', 'PGPASSWORD=' + password,
                '-v', f'{Path(__file__).resolve().parent}:/bundle:ro',
                '-v', f'{output_dir}:/review', '--entrypoint=node', node_image, '/review/roundtrip-client.cjs'])
        restored = json.loads(sql('bundle_restored', SNAPSHOT))
        if original != restored:
            raise AssertionError('Roundtrip changed fixture rows, sequence state, functions, constraints or large objects')
        client = json.loads((output_dir / 'client-execution.json').read_text())
        dump = (output_dir / 'fixture.dump').read_bytes()
        canonical = json.dumps(original, sort_keys=True, ensure_ascii=False).encode()
        result = {'passed': True, 'platform': 'linux/amd64', 'serverImage': package.IMAGE,
                  'clientVersion': json.loads((Path(__file__).with_name(package.MANIFEST)).read_text())['tools'],
                  'tls': client['tls'], 'authentication': 'scram-sha-256', 'hostLookup': 'Docker private DNS name',
                  'archiveBytes': len(dump), 'archiveSha256': hashlib.sha256(dump).hexdigest(),
                  'sourceAndRestoredFixtureSha256': hashlib.sha256(canonical).hexdigest(),
                  'preserved': ['UUID', 'exact numeric(40,0)', 'JSONB nested numeric and Unicode', 'bytea/NULL/zero/arrays',
                                'identity and custom sequences', 'foreign keys', 'SQL functions', 'views/materialized views',
                                'pgcrypto extension', 'large objects'],
                  'dumpStderr': client['dumpStderr'], 'restoreStderr': client['restoreStderr'],
                  'existingContainersBefore': before}
        (output_dir / 'result.json').write_text(json.dumps(result, indent=2) + '\n')
        print(json.dumps(result, ensure_ascii=False), flush=True)
    finally:
        if started:
            subprocess.run(['docker', 'rm', '--force', name], capture_output=True, timeout=30)
        if network_created:
            subprocess.run(['docker', 'network', 'rm', network], capture_output=True, timeout=30)
        after = docker(['ps', '-q']).stdout.splitlines()
        if sorted(before) != sorted(after):
            raise RuntimeError('Running-container inventory changed unexpectedly')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', default='/tmp/antsurvival-pg-client-review/roundtrip')
    parser.add_argument('--node-image', default='antsurvival-api-runtime-check:20261026')
    args = parser.parse_args()
    test(args.output_dir, args.node_image)
